new_eeg <- function(data, channels, sampling_rate, times = NULL,
                    events = NULL, metadata = NULL, reference = "unknown",
                    preprocessing_history = list()) {
  structure(
    list(
      data                  = data,
      channels              = channels,
      sampling_rate         = sampling_rate,
      times                 = times,
      events                = events,
      metadata              = metadata,
      reference             = reference,
      preprocessing_history = preprocessing_history
    ),
    class = "eeg"
  )
}

