  design <- function(l = NULL, h = NULL, ltb = "auto", htb = "auto",
                     len = "auto", win = "hamming") {
    .make_bandpass_filter(256, l, h, "fir", NULL, ltb, htb, len, win,
                          "zero", "reflect_limited")
  }

  # the automatic rules
  d <- design(1, 40)
