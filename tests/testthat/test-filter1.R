  expect_equal(dim(ym), c(2L, 1500L))
  expect_equal(dimnames(ym), dimnames(m))

  # a vector gives the numbers of the same row inside a matrix
  expect_identical(filter_data(m[2, ], 256, l_freq = 1, h_freq = 40), unname(ym[2, ]))

