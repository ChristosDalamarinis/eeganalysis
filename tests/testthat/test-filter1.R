test_that(".overlap_add_filter attenuates stop-band content", {
  sfreq <- 256
  t     <- seq(0, 4 - 1/sfreq, by = 1/sfreq)   # 1024 samples
  # 10 Hz (pass) + 80 Hz (stop for 40 Hz low-pass)
  x     <- sin(2 * pi * 10 * t) + sin(2 * pi * 80 * t)
  h     <- .firwin_lowpass(851L, 40 / 128)
  y     <- .overlap_add_filter(x, h)
  # A zero-phase FIR of length N needs (N-1)/2 samples of real signal on each
  # side of every output point; within that reach of either edge, .overlap_add_
  # filter() is convolving against reflect_limited's mirrored (not real) data,
  # so the residual there depends on the signal's phase at that edge - trimming
  # only the start (as this test previously did) leaves it dependent on the
  # phase at the *end*, which is what made it fail intermittently. Trim both.
  reach   <- (length(h) - 1L) %/% 2L
  y_mid   <- y[(reach + 1L):(length(y) - reach)]
  ref_mid <- sin(2 * pi * 10 * t[(reach + 1L):(length(t) - reach)])
  expect_lt(sd(y_mid - ref_mid), 0.01)
})

