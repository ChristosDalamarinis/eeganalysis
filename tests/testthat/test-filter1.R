  y <- eeg_notch(eeg, freqs = freqs, method = "iir", phase = phase,
                 verbose = FALSE, ...)$data[1, ]
  expect_lt(max(abs(y[idx] - ref)), 1e-8)
  expect_equal(sum(y^2), ss, tolerance = 1e-8)
}

